package exercise;

public class Application {
    public static void main(String[] args) {
        /*
         * chap01 literal_and_variable 연습문제
         *
         * 각 문제는 별도의 클래스와 main 메서드를 만들어 해결한다.
         * 출력 결과를 그대로 문자열로 작성하지 말고 문제에서 요구한 리터럴, 변수,
         * 상수, 형변환을 사용한다.
         */

        /*
         * 문제 1. 여러 종류의 리터럴 출력
         *
         * 다음 값을 알맞은 형태의 리터럴로 직접 출력한다.
         * - 문자열 Java
         * - 정수 100
         * - 실수 3.14
         * - 문자 A
         * - 논리값 true
         *
         * 실행 결과
         * Java
         * 100
         * 3.14
         * A
         * true
         */

        /*
         * 문제 2. 자기소개 정보 저장
         *
         * 다음 정보를 저장할 수 있는 적절한 자료형의 변수를 선언하고 값을 대입한다.
         * - 이름: 홍길동
         * - 나이: 20
         * - 키: 175.5
         * - 학점: A
         * - 재학 여부: true
         *
         * 실행 결과
         * 이름 : 홍길동
         * 나이 : 20세
         * 키 : 175.5cm
         * 학점 : A
         * 재학 여부 : true
         */

        /*
         * 문제 3. 상수를 이용한 상품 금액 계산
         *
         * 상품명, 상품 단가, 구매 수량을 상수로 선언한다.
         * - 상품명: 키보드
         * - 상품 단가: 12000
         * - 구매 수량: 3
         * 단가와 수량을 곱한 결과를 totalPrice 변수에 저장하여 출력한다.
         * 상수 이름은 대문자와 밑줄을 사용한다.
         *
         * 실행 결과
         * 상품명 : 키보드
         * 단가 : 12000원
         * 수량 : 3개
         * 총 금액 : 36000원
         */

        /*
         * 문제 4. 오버플로우와 계산 자료형 확인
         *
         * 1. byte 변수 max에 127을 저장한 뒤 1 증가시켜 출력한다.
         * 2. byte 변수 min에 -128을 저장한 뒤 1 감소시켜 출력한다.
         * 3. int 변수 firstNumber에 1_000_000, secondNumber에 700_000을 저장한다.
         * 4. 두 int를 먼저 곱한 결과를 long에 저장하여 출력한다.
         * 5. firstNumber를 long으로 형변환한 뒤 곱한 결과를 출력한다.
         *
         * 실행 결과
         * byte 최댓값에서 1 증가 : -128
         * byte 최솟값에서 1 감소 : 127
         * int로 계산한 결과 : -79669248
         * long으로 계산한 결과 : 700000000000
         */

        /*
         * 문제 5. 형변환을 이용한 평균 계산
         *
         * 국어 80점, 영어 75점, 수학 90점을 int 변수에 저장한다.
         * 총점을 int 변수에 저장하고, 평균이 실수로 나오도록 명시적 형변환을 사용한다.
         * 문자 'A'를 char 변수에 저장한 뒤 int로 자동 형변환하여 유니코드 값을 출력한다.
         *
         * 실행 결과
         * 총점 : 245
         * 평균 : 81.66666666666667
         * A의 유니코드 값 : 65
         */
    }
}
