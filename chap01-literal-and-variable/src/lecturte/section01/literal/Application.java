package lecturte.section01.literal;

public class Application {
    public static void main(String[] args) {
        // 숫자 형태의 값
        // 단축키 : sout
        System.out.println(123); // 정수형
        System.out.println(1.23); // 실수형

        // 문자 형태의 값 : 작은 따음표
        System.out.println('a'); // 문자형
        // System.out.println('');  비어있으면 오류
        // System.out.println('ab'); //두개 이상의 문자는 오류


        // 문자열 형태의 값 : 큰 따음표
        System.out.println("안녕하세요");
        System.out.println("a");
        System.out.println("");
        System.out.println("---------------");
        System.out.println("1234"); // 문자열은 큰 따음표를 붙인다
        System.out.println(1234); // 숫자형은 큰 따음표 없이 사용

        // 논리형태의 값
        System.out.println(true);
        System.out.println(false);



    }
}
