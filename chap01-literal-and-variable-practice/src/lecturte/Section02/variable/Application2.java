package lecturte.Section02.variable;

public class Application2 {
    public static void main(String[] args) {

        /*
        ==변수를 사용하는 방법==
        1.변수를 준비, 선언한다.
        2.변수에 값을 대입한다 (초기화, 대입)
        * */

        //선언 : 자료형 + 변수형
        int age = 20;

        //정수형 (기본형 int)
        byte hunm;
        short sunm;
        int iunm;
        long lunm = 3_000_000_000L; // int 범주는 넘는 정수 리터럴에는 L

        // 실수형 (기본형 double)
        float funm =4.0f;
        double dunm;

        char ch; // 기본 문자형
        boolean isTrue; //논리형

        //문자열 (참조자료형)
        String str;
    }
}
