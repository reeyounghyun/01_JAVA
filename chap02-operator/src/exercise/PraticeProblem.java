package exercise;

public class PraticeProblem {
    public static void main(String[] args) {
        /*
         * chap02 operator 연습문제
         *
         * 각 문제는 별도의 클래스와 main 메서드를 만들어 해결한다.
         * 아직 배우지 않은 조건문(if, switch)은 사용하지 않고 연산자를 이용한다.
         * 먼저 실행 결과를 예상한 뒤 코드를 작성하고 실행한다.
         */

        /*
         * 문제 1. 초를 분과 초로 변환
         *
         * totalSeconds 변수에 125를 저장한다.
         * / 연산자로 분을 계산하고 % 연산자로 남은 초를 계산한다.
         * 계산한 결과는 각각 minutes와 seconds 변수에 저장한다.
         *
         * 실행 결과
         * 125초는 2분 5초입니다.
         */

        /*
         * 문제 2. 복합 대입 연산자와 후위 증가
         *
         * point 변수의 초기값은 1000이다.
         * 다음 계산을 복합 대입 연산자로 순서대로 처리한다.
         * 1. 500을 더한다.
         * 2. 200을 뺀다.
         * 3. 2를 곱한다.
         * 4. 4로 나눈다.
         *
         * 계산이 끝난 point를 후위 증가시키면서 beforeIncrease 변수에 대입한다.
         * 복합 대입 직후 값, 후위 증가식이 반환한 값, 증가가 끝난 현재 값을 출력한다.
         *
         * 실행 결과
         * 복합 대입 후 포인트 : 650
         * 후위 증가식이 반환한 값 : 650
         * 후위 증가 후 현재 포인트 : 651
         */

        /*
         * 문제 3. 실수와 문자열 비교
         *
         * 1. 0.1 + 0.2의 결과를 double 변수 sum에 저장한다.
         * 2. sum의 값과 sum == 0.3의 결과를 출력한다.
         * 3. savedId에는 문자열 리터럴 "java"를 저장한다.
         * 4. inputId에는 new String("java")로 만든 문자열을 저장한다.
         * 5. 두 문자열을 ==와 equals()로 각각 비교하여 결과를 출력한다.
         *
         * 실행 결과
         * 0.1 + 0.2 : 0.30000000000000004
         * 0.3과 같은가? : false
         * == 비교 결과 : false
         * equals 비교 결과 : true
         */

        /*
         * 문제 4. 논리 연산자와 단락 평가
         *
         * age는 20, hasTicket은 true로 선언한다.
         * age가 19 이상이면서 티켓이 있는지 검사하여 canEnter에 저장한다.
         * age가 7 이하이거나 65 이상인지 검사하여 hasFreeAdmission에 저장한다.
         *
         * numerator는 10, denominator는 0으로 선언한다.
         * denominator가 0이 아니면서 나눗셈 결과가 2보다 큰지 검사한다.
         * 단락 평가를 이용하여 0으로 나누는 연산이 실행되지 않도록 작성한다.
         *
         * 실행 결과
         * 입장 가능 여부 : true
         * 무료입장 여부 : false
         * 안전한 나눗셈 조건 결과 : false
         */

        /*
         * 문제 5. 삼항 연산자로 숫자 분류
         *
         * number 변수에 -7을 저장한다.
         * 중첩 삼항 연산자를 사용해 양수, 0, 음수 중 하나를 sign에 저장한다.
         * 삼항 연산자와 % 연산자를 사용해 짝수 또는 홀수를 parity에 저장한다.
         * if와 switch는 사용하지 않는다.
         *
         * 실행 결과
         * -7은 음수이면서 홀수입니다.
         */
    }
}
